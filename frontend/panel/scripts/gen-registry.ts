// Collects the core modules' panel screens (PRD E8 §7) into src/generated/registry.ts, and the
// English source messages (the framework's `ui` and `panel`, and each core module's own) into
// src/generated/messages.ts.
// Only src/agento/modules/ is scanned: a user (app/code) or PyPI module never ships panel
// JavaScript into the origin that holds the session cookie.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { assertPanelModule } from "../../packages/api/src/contract.ts";

const PANEL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const MODULES_DIR = resolve(PANEL, "../../src/agento/modules");
const OUT = join(PANEL, "src/generated/registry.ts");
export const FRAMEWORK_I18N_DIR = resolve(PANEL, "../../src/agento/framework/i18n");
const MESSAGES_OUT = join(PANEL, "src/generated/messages.ts");
const FRAMEWORK_NAMESPACES = ["ui", "panel"];
const SOURCE_FILE = "en.json";

export async function collect(modulesDir = MODULES_DIR): Promise<string[]> {
  const found: string[] = [];
  for (const dir of readdirSync(modulesDir).sort()) {
    const entry = join(modulesDir, dir, "panel", "index.ts");
    if (!existsSync(entry)) continue;
    const mod = await import(pathToFileURL(entry).href);
    assertPanelModule(dir, mod.default);
    found.push(dir);
  }
  return found;
}

export function render(dirs: string[], modulesDir = MODULES_DIR): string {
  const rel = (d: string) => relative(dirname(OUT), join(modulesDir, d, "panel", "index.ts")).split("\\").join("/");
  return [
    "// Generated by panel/scripts/gen-registry.ts; do not edit.",
    'import { assertPanelModule, type PanelModule } from "@agento/api";',
    ...dirs.map((d, i) => `import m${i} from "${rel(d)}";`),
    "",
    "export const MODULES: PanelModule[] = [",
    ...dirs.map((d, i) => `  assertPanelModule(${JSON.stringify(d)}, m${i}),`),
    "];",
    "",
  ].join("\n");
}

export interface SourceCatalog { namespace: string; file: string }

/** The framework's two namespaces first, then every core module that ships `i18n/en.json`. */
export function collectSourceCatalogs(modulesDir = MODULES_DIR, frameworkDir = FRAMEWORK_I18N_DIR): SourceCatalog[] {
  const framework = FRAMEWORK_NAMESPACES.map((namespace) => ({ namespace, file: join(frameworkDir, namespace, SOURCE_FILE) }));
  const modules = readdirSync(modulesDir).sort()
    .map((namespace) => ({ namespace, file: join(modulesDir, namespace, "i18n", SOURCE_FILE) }))
    .filter((c) => existsSync(c.file));
  return [...framework, ...modules];
}

export function renderMessages(catalogs: SourceCatalog[]): string {
  const rel = (file: string) => relative(dirname(MESSAGES_OUT), file).split("\\").join("/");
  return [
    "// Generated by panel/scripts/gen-registry.ts; do not edit.",
    'import type { Messages } from "@agento/ui";',
    ...catalogs.map((c, i) => `import c${i} from "${rel(c.file)}";`),
    "",
    "export const SOURCE_MESSAGES: Messages = {",
    ...catalogs.map((c, i) => `  ${JSON.stringify(c.namespace)}: c${i},`),
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dirs = await collect();
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, render(dirs));
  writeFileSync(MESSAGES_OUT, renderMessages(collectSourceCatalogs()));
}
